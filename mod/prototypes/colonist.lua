-- SPIKE (#1): colonist as a `unit` prototype.
-- Cloned from small-biter so all required unit fields (animations, attack_parameters,
-- collision, etc.) are valid; art is placeholder.
local colonist = table.deepcopy(data.raw["unit"]["small-biter"])
colonist.name = "colony-colonist"
colonist.localised_name = {"entity-name.colony-colonist"}
colonist.minable = nil
colonist.loot = nil
colonist.corpse = nil
colonist.max_health = 100
colonist.movement_speed = 0.08
colonist.vision_distance = 1          -- try to avoid auto-aggro / wandering
colonist.distraction_cooldown = 1000000
colonist.spawning_time_modifier = nil
colonist.absorptions_to_join_attack = nil
colonist.ai_settings = {
  destroy_when_commands_fail = false,
  allow_try_return_to_spawner = false,
  do_separation = true,
}
colonist.flags = {"placeable-off-grid", "not-repairable", "breaths-air"}
-- Art: generated by scripts/gen_art.py. colonist.png is the idle frame; colonist-run.png is an 8-frame run strip.
local G = "__colony-bio-logistics__/graphics/"
local function anim(file, frames)
  local common = {width = 64, height = 64, direction_count = 1, frame_count = frames, line_length = frames,
    scale = 0.6, animation_speed = 0.5}
  local main, shadow = table.deepcopy(common), table.deepcopy(common)
  main.filename = G .. file .. ".png"
  shadow.filename = G .. file .. "-shadow.png"; shadow.width = 128; shadow.draw_as_shadow = true
  return {layers = {main, shadow}}
end
local person = anim("colonist", 1)
local run = anim("colonist-run", 8)
colonist.run_animation = run
-- Hunting (#79): a colonist can take a shot *when commanded*. Hitscan (`instant` delivery) rather than a
-- projectile entity: nothing to spawn per shot, and a shot cannot miss a moving animal. The long range is what
-- lets a hunter work from outside the animal's reach. `vision_distance` stays at 1 and nothing auto-targets,
-- so a colonist still never starts a fight on its own.
colonist.attack_parameters = {
  type = "projectile",
  range = 14,
  cooldown = 40,
  cooldown_deviation = 0.1,
  ammo_category = "bullet",
  ammo_type = {
    target_type = "entity",
    action = {type = "direct", action_delivery = {type = "instant",
      target_effects = {type = "damage", damage = {amount = 10, type = "physical"}}}},
  },
  animation = table.deepcopy(person),
  sound = {filename = "__base__/sound/fight/defender-gunshot-1.ogg", volume = 0.25},
}
colonist.icon = "__colony-bio-logistics__/graphics/colonist.png"; colonist.icon_size = 64; colonist.icons = nil
colonist.selection_box = {{-0.4, -0.7}, {0.4, 0.4}}
-- Spike #1 variant: does a unit load without attack_parameters at all?
if settings.startup["colony-spike-no-attack"].value then
  colonist.attack_parameters = nil
end
data:extend({colonist})
